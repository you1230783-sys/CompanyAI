# 固定的 Python 離線環境；只在開發／建置時執行，使用者端不執行 pip。
[CmdletBinding()]
param([string]$Destination, [switch]$RefreshManifest)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
if (-not $Destination) { $Destination = Join-Path $root '.build\python-runtime' }
$Destination = [IO.Path]::GetFullPath($Destination)
$archive = Join-Path $root 'offline\python-inputs.zip'
$lock = Get-Content -LiteralPath (Join-Path $root 'offline\python-lock.json') -Raw | ConvertFrom-Json
if ((Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $lock.archive_sha256) { throw 'Python offline archive checksum mismatch.' }
$inputs = Join-Path $root '.build\python-inputs'
New-Item -ItemType Directory -Path $inputs -Force | Out-Null
Expand-Archive -LiteralPath $archive -DestinationPath $inputs -Force
foreach ($entry in $lock.files) {
    if ([IO.Path]::GetFileName($entry.name) -ne $entry.name) { throw 'Invalid Python input filename.' }
    $path = Join-Path $inputs $entry.name
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant() -ne $entry.sha256) { throw "Python input checksum mismatch: $($entry.name)" }
}
# 新目錄重建，避免把舊版模組、開發機 site-packages 或快取混入交付。
if (Test-Path -LiteralPath $Destination) { throw "Python destination must be new: $Destination" }
New-Item -ItemType Directory -Path $Destination -Force | Out-Null
Expand-Archive -LiteralPath (Join-Path $inputs $lock.python_archive) -DestinationPath $Destination
$packages = Join-Path $Destination 'Lib\site-packages'
New-Item -ItemType Directory -Path $packages -Force | Out-Null
Add-Type -AssemblyName System.IO.Compression.FileSystem
foreach ($entry in $lock.files | Where-Object { $_.name -like '*.whl' }) {
    [IO.Compression.ZipFile]::ExtractToDirectory((Join-Path $inputs $entry.name), $packages)
}
# 明確隔離使用者 PATH／登錄／site-packages；不啟用 site 或自動執行 .pth。
@('python313.zip', '.', 'Lib\site-packages') | Set-Content -LiteralPath (Join-Path $Destination 'python313._pth') -Encoding ASCII
Copy-Item -LiteralPath (Join-Path $root 'src\projects\python_worker.py') -Destination (Join-Path $Destination 'lm_worker.py')
$fontDirectory = Join-Path $Destination 'LMFonts'
New-Item -ItemType Directory -Path $fontDirectory | Out-Null
Copy-Item -LiteralPath (Join-Path $root 'ui/fonts/jf-openhuninn-2.1.ttf') -Destination $fontDirectory
Copy-Item -LiteralPath (Join-Path $root 'ui/fonts/HUNINN-LICENSE.txt') -Destination $fontDirectory
# 只移除名稱完全相同的 tests；testing、_testing、_lib 都是執行時相依，不可誤刪。
# 輸出逐目錄清單及總量，方便每次升級套件時審查實際刪除範圍。
$before = @(Get-ChildItem -LiteralPath $Destination -Recurse -File)
$removedTests = @()
# NumPy 2.2.6 的 testing 會直接 import 此模組，SciPy 也會間接使用。
# 實測全刪會使 scipy.optimize 無法載入；只保留這一個 wheel 原檔（namespace package 無 __init__.py）。
$requiredTestModule = 'numpy\_core\tests\_natype.py'
$requiredTestBytes = [IO.File]::ReadAllBytes((Join-Path $packages $requiredTestModule))
$packagePrefix = [IO.Path]::GetFullPath($packages) + [IO.Path]::DirectorySeparatorChar
foreach ($directory in @(Get-ChildItem -LiteralPath $packages -Directory -Recurse | Where-Object Name -CEQ 'tests' | Sort-Object { $_.FullName.Length } -Descending)) {
    $resolvedTests = [IO.Path]::GetFullPath($directory.FullName)
    if (-not $resolvedTests.StartsWith($packagePrefix, [StringComparison]::OrdinalIgnoreCase) -or
        $directory.Name -cne 'tests' -or ($directory.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
        throw 'Unsafe Python tests pruning path.'
    }
    $items = @(Get-ChildItem -LiteralPath $resolvedTests -Recurse -Force)
    if (@($items | Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint }).Count) { throw 'Python package contains a link.' }
    $testFiles = @($items | Where-Object { -not $_.PSIsContainer })
    $removedTests += [ordered]@{path=$resolvedTests.Substring($Destination.Length + 1); files=$testFiles.Count; bytes=($testFiles | Measure-Object Length -Sum).Sum}
    Write-Host "Remove package tests: $resolvedTests ($($testFiles.Count) files)"
    Remove-Item -LiteralPath $resolvedTests -Recurse -Force
}
$requiredTestPath = Join-Path $packages $requiredTestModule
New-Item -ItemType Directory -Path (Split-Path $requiredTestPath -Parent) -Force | Out-Null
[IO.File]::WriteAllBytes($requiredTestPath, $requiredTestBytes)
Write-Host "Retain required runtime import: $requiredTestModule"
$afterPruning = @(Get-ChildItem -LiteralPath $Destination -Recurse -File)
$runtimePython = Join-Path $Destination 'python.exe'
& $runtimePython -I -B -c 'import sys; assert sys.version_info[:3] == (3,13,12), sys.version'
if ($LASTEXITCODE -ne 0) { throw 'Bytecode must be generated by Python 3.13.12.' }
# 固定 co_filename 的根路徑，避免不同建置資料夾產生不同 pyc 雜湊。
# unchecked-hash 不受安裝時間戳影響；py 與 pyc 都由下方清單完整驗證。
& $runtimePython -I -B -m compileall -q --invalidation-mode unchecked-hash -j 0 -s $Destination -p /LM_AI/python (Join-Path $Destination 'Lib')
if ($LASTEXITCODE -ne 0) { throw 'Python bytecode compilation failed; inspect the reported files instead of ignoring errors.' }
$afterBytecode = @(Get-ChildItem -LiteralPath $Destination -Recurse -File)
[ordered]@{
    before_files=$before.Count; before_bytes=($before | Measure-Object Length -Sum).Sum
    removed_test_directories=$removedTests
    retained_runtime_import=$requiredTestModule
    pruned_files=$afterPruning.Count; pruned_bytes=($afterPruning | Measure-Object Length -Sum).Sum
    final_files=$afterBytecode.Count; final_bytes=($afterBytecode | Measure-Object Length -Sum).Sum
    pyc_files=@($afterBytecode | Where-Object Extension -CEQ '.pyc').Count
} | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath ($Destination + '-build-report.json') -Encoding UTF8
& $runtimePython -I -B (Join-Path $PSScriptRoot 'Test-PythonRuntime.py')
if ($LASTEXITCODE -ne 0) { throw 'Pruned Python runtime scientific operations failed.' }
& (Join-Path $Destination 'python.exe') -I -B -c 'import sys,pandas,numpy,openpyxl,scipy,matplotlib; print(sys.version); print(pandas.__version__,numpy.__version__,openpyxl.__version__,scipy.__version__,matplotlib.__version__)'
if ($LASTEXITCODE -ne 0) { throw 'Offline Python import verification failed.' }
# 保存每個檔案雜湊，原生啟動端核對後才允許執行模型程式。
$manifest = @()
Get-ChildItem -LiteralPath $Destination -Recurse -File | Sort-Object FullName | ForEach-Object {
    $manifest += [ordered]@{ path = $_.FullName.Substring($Destination.Length + 1).Replace('\','/'); sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant(); size = $_.Length }
}
$json = ConvertTo-Json -InputObject $manifest -Depth 4 -Compress
$pinnedManifest = Join-Path $root 'assets\python-runtime-manifest.json'
$pinnedHash = Join-Path $root 'assets\python-runtime-sha256.txt'
if ($RefreshManifest) {
    # 僅在維護者刻意更新 worker／依賴時改版；一般離線建置不能改信任基準。
    [IO.File]::WriteAllText($pinnedManifest, $json, (New-Object Text.UTF8Encoding($false)))
    [IO.File]::WriteAllText($pinnedHash, (Get-FileHash -LiteralPath $pinnedManifest).Hash.ToLowerInvariant() + "`n", (New-Object Text.UTF8Encoding($false)))
    # 清理只信任曾明確登記的清單，不能憑 trash 目錄內自稱的雜湊刪檔。
    $historyPath = Join-Path $root 'assets\python-runtime-history.json'
    $history = @(Get-Content -LiteralPath $historyPath -Raw | ConvertFrom-Json)
    $history += (Get-Content -LiteralPath $pinnedHash -Raw).Trim()
    [IO.File]::WriteAllText($historyPath, (ConvertTo-Json -InputObject @($history | Sort-Object -Unique)) + "`n", (New-Object Text.UTF8Encoding($false)))
}
if ((Get-FileHash -LiteralPath $pinnedManifest).Hash.ToLowerInvariant() -ne (Get-Content -LiteralPath $pinnedHash -Raw).Trim()) { throw 'Pinned Python manifest/hash disagree.' }
# PowerShell 5.1／7 的文化排序不同。比較檔案集合與 bytes，而非重新序列化後的排列；
# 驗證全部通過才複製同一份固定清單，確保不同建置環境產生完全相同的 runtime。
$actual = @{}
foreach ($entry in $manifest) { $actual[$entry.path] = $entry }
$expected = Get-Content -LiteralPath $pinnedManifest -Raw | ConvertFrom-Json
if ($actual.Count -ne $expected.Count) { throw 'Rebuilt Python file count differs from the pinned manifest.' }
foreach ($entry in $expected) {
    $rebuilt = $actual[$entry.path]
    if (-not $rebuilt -or $rebuilt.sha256 -ne $entry.sha256 -or $rebuilt.size -ne $entry.size) { throw "Rebuilt Python differs: $($entry.path). Review the changes and use -RefreshManifest only for an intentional runtime update." }
}
Copy-Item -LiteralPath $pinnedManifest -Destination (Join-Path $Destination 'runtime-manifest.json')
Write-Host "Offline Python ready: $Destination"
